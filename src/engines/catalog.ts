export function descriptor(id: FormatId): FormatDescriptor {
  return DESCRIPTORS[id];
}

export function formatsByCategory(): { category: FormatCategory; formats: FormatDescriptor[] }[] {
  const cats: FormatCategory[] = ['data', 'web', 'programming', 'api', 'advanced'];
  return cats.map((category) => ({ category, formats: FORMAT_ORDER.map((id) => DESCRIPTORS[id]).filter((d) => d.category === category) }));
}

export function formatForExtension(fileName: string): FormatId | null {
  const lower = fileName.toLowerCase();
  if (lower === '.env' || lower.startsWith('.env.') || lower.endsWith('.env')) return 'env';
  const ext = lower.includes('.') ? lower.slice(lower.lastIndexOf('.') + 1) : '';
  if (!ext) return null;
  for (const id of FORMAT_ORDER) if (DESCRIPTORS[id].extensions.includes(ext)) return id;
  return null;
}

export function fileExtensionFor(id: FormatId): string {
  if (id === 'env') return 'env';
  if (id === 'openapi') return 'yaml';
  if (id === 'jsonschema') return 'schema.json';
  return DESCRIPTORS[id].extensions[0] ?? 'txt';
}

export function mimeTypeFor(id: FormatId): string {
  return DESCRIPTORS[id].mimeTypes[0] ?? (DESCRIPTORS[id].binary ? 'application/octet-stream' : 'text/plain');
}
